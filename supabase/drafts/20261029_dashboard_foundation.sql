-- Grant only sequence USAGE where inserts rely on a serial/identity default.
-- Identity-backed inserts may not require this, but the grant is harmless.
do $block$
declare
  target record;
  sequence_name text;
begin
  for target in
    select *
    from (values
      ('admissions', 'anon, authenticated'),
      ('consultations', 'anon'),
      ('contacts', 'anon'),
      ('courses', 'authenticated'),
      ('subscribers', 'anon')
    ) as sequence_access(table_name, grantees)
  loop
    sequence_name := pg_get_serial_sequence(
      format('public.%I', target.table_name),
      'id'
    );
    if sequence_name is not null then
      execute format(
        'grant usage on sequence %s to %s',
        sequence_name,
        target.grantees
      );
    end if;
  end loop;
end
$block$;


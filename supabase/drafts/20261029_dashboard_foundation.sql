-- REVIEW DRAFT ONLY. Do not execute until the schema, role-claim provisioning,
-- and policy behavior have been reviewed and approved.
--
-- This draft is additive: it does not delete existing records, auto-link
-- accounts by email, create an administrator, or use a service-role key.
-- Public intake is limited by RLS; administrator checks use the trusted
-- app_metadata role claim, not user-editable user_metadata.

begin;

-- Remove table-level capabilities that browser roles do not need. In
-- particular, RLS does not protect tables from TRUNCATE.
revoke truncate, trigger, references
  on table public.admissions,
            public.consultations,
            public.contacts,
            public.courses,
            public.reviews,
            public.students,
            public.subscribers
  from anon, authenticated;

-- A trusted server-side process must set app_metadata.role = 'admin' after
-- independently verifying the administrator. Never set this from the client.
create or replace function public.is_jhorka_admin()
returns boolean
language sql
stable
set search_path = ''
as $function$
  select coalesce(auth.jwt() -> 'app_metadata' ->> 'role' = 'admin', false);
$function$;

revoke all on function public.is_jhorka_admin() from public;
grant execute on function public.is_jhorka_admin() to authenticated;

-- Link a verified Supabase Auth account to a student record only after
-- separately verifying identity. Existing records are deliberately not
-- matched automatically by email.
alter table public.students
  add column if not exists auth_user_id uuid;

create unique index if not exists students_auth_user_id_unique
  on public.students (auth_user_id)
  where auth_user_id is not null;

do $block$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'students_auth_user_id_fkey'
      and conrelid = 'public.students'::regclass
  ) then
    alter table public.students
      add constraint students_auth_user_id_fkey
      foreign key (auth_user_id) references auth.users (id)
      on delete set null;
  end if;
end
$block$;

-- Link future admissions to a verified student account. NULL keeps public
-- applications available without forcing registration or account linking.
alter table public.admissions
  add column if not exists student_id bigint;

create index if not exists admissions_student_id_idx
  on public.admissions (student_id)
  where student_id is not null;

do $block$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'admissions_student_id_fkey'
      and conrelid = 'public.admissions'::regclass
  ) then
    alter table public.admissions
      add constraint admissions_student_id_fkey
      foreign key (student_id) references public.students (id)
      on delete restrict;
  end if;
end
$block$;

-- Record future application status changes without rewriting existing rows.
create table if not exists public.admission_status_history (
  id bigint generated by default as identity primary key,
  admission_id bigint not null
    references public.admissions (id) on delete restrict,
  previous_status text,
  new_status text not null,
  changed_by uuid references auth.users (id) on delete set null,
  changed_at timestamptz not null default now()
);

alter table public.admission_status_history enable row level security;

create or replace function public.record_admission_status_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if new.status is distinct from old.status then
    insert into public.admission_status_history (
      admission_id,
      previous_status,
      new_status,
      changed_by
    )
    values (
      new.id,
      old.status,
      new.status,
      auth.uid()
    );
  end if;

  return new;
end;
$function$;

revoke all on function public.record_admission_status_change() from public;

drop trigger if exists jhorka_record_admission_status_change
  on public.admissions;

create trigger jhorka_record_admission_status_change
after update of status on public.admissions
for each row
execute function public.record_admission_status_change();

-- Contact messages have no status column in the current schema.
alter table public.contacts
  add column if not exists status text not null default 'unread';

-- Archived courses retain their IDs for existing admission foreign keys.
alter table public.courses
  add column if not exists is_published boolean not null default true,
  add column if not exists is_archived boolean not null default false;

-- The existing public course policy allows every course. Replace it with a
-- published-and-not-archived filter; admin access is separately policy-bound.
drop policy if exists "Public courses read" on public.courses;

create policy "Public courses read"
  on public.courses
  for select
  to anon
  using (is_published and not is_archived);

grant select on public.courses to anon, authenticated;
grant insert, update on public.courses to authenticated;

create policy "jhorka_admin_courses_read"
  on public.courses
  for select
  to authenticated
  using (public.is_jhorka_admin());

create policy "jhorka_admin_courses_insert"
  on public.courses
  for insert
  to authenticated
  with check (public.is_jhorka_admin());

create policy "jhorka_admin_courses_update"
  on public.courses
  for update
  to authenticated
  using (public.is_jhorka_admin())
  with check (public.is_jhorka_admin());

create policy "jhorka_authenticated_published_courses_read"
  on public.courses
  for select
  to authenticated
  using (
    (is_published and not is_archived)
    or public.is_jhorka_admin()
  );

-- Public admission submissions must meet the existing pending-status rule.
-- Authenticated submissions may link only to the caller's own student row.
drop policy if exists "Public admission submission" on public.admissions;

create policy "Public admission submission"
  on public.admissions
  for insert
  to anon
  with check (status = 'pending' and student_id is null);

grant insert on public.admissions to anon, authenticated;
grant select, update on public.admissions to authenticated;

create policy "jhorka_authenticated_admission_submission"
  on public.admissions
  for insert
  to authenticated
  with check (
    status = 'pending'
    and (
      student_id is null
      or exists (
        select 1
        from public.students s
        where s.id = student_id
          and s.auth_user_id = (select auth.uid())
      )
    )
  );

create policy "jhorka_admin_admissions_read"
  on public.admissions
  for select
  to authenticated
  using (public.is_jhorka_admin());

create policy "jhorka_admin_admissions_update"
  on public.admissions
  for update
  to authenticated
  using (public.is_jhorka_admin())
  with check (public.is_jhorka_admin());

create policy "jhorka_student_own_admissions_read"
  on public.admissions
  for select
  to authenticated
  using (
    student_id in (
      select s.id
      from public.students s
      where s.auth_user_id = (select auth.uid())
    )
  );

